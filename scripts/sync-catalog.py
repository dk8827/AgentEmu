"""Validate the release catalog and generate bundled-model code and user tables."""

import argparse
import json
from pathlib import Path
from model_evidence import matches_policy_contract

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
games = json.loads((ROOT / "catalog/games.json").read_text())
models = json.loads((ROOT / "catalog/models.json").read_text())
by_hash = {g["sha256"]: g for g in games}
assert len(by_hash) == len(games), "Duplicate cartridge identity"
assert {m["id"] for m in models} == {p.name for p in (ROOT / "models").iterdir() if p.is_dir()}
q = lambda value: json.dumps(value, ensure_ascii=False)
rust = "// Generated by scripts/sync-catalog.py; edit catalog/models.json.\nvec![\n"
rows = []
for model in models:
    folder = ROOT / "models" / model["id"]
    manifest = json.loads((folder / "manifest.json").read_text())
    game = by_hash[manifest["rom_sha256"]]
    task = next(
        (
            t
            for p in (ROOT / "integrations").glob("*/task.json")
            if matches_policy_contract(t := json.loads(p.read_text()), manifest)
        ),
        None,
    )
    if task is None:
        raise ValueError(
            f"{model['id']}: cartridge, observation and architecture do not match a declared task contract"
        )
    assert model["status"] in ("recommended", "experimental", "research")
    if model["bundled"]:
        rust += f"    model!({q(model['id'])}, {q(model['notes'])}, {str(model['status'] != 'recommended').lower()}),\n"
    rows.append(
        f"| {game['title']} | [{model['id']}](../models/{model['id']}/README.md) | {task['scope']} | {model['status']} | {'Yes' if model['bundled'] else 'CLI only'} |"
    )
rust += "]\n"
doc = (
    """# Agent catalog

Generated from `catalog/models.json`, model manifests and integration contracts.
Status is a maintainer recommendation, not a guarantee of completion. The gallery
starts with the first included model listed for each game; other included models
are available under Agent details. Model cards contain results and failure cases.
Shared ownership
works with each bundled model; assistance-specific training is experimental.

| Game | Model | Section | Status | Included in player |
| --- | --- | --- | --- | --- |
"""
    + "\n".join(rows)
    + "\n"
)
art = "// Generated by scripts/sync-catalog.py; edit catalog/games.json.\nmatch hash {\n"
for game in games:
    if game.get("gallery_art"):
        name = game["gallery_art"]
        assert name.replace("-", "").isalnum(), "Invalid gallery asset name"
        assert (ROOT / f"crates/player-ui/assets/gallery/{name}.png").is_file()
        art += f'    {q(game["sha256"])} => ({q(game.get("gallery_title", game["title"]))}, include_bytes!("../assets/gallery/{name}.png")),\n'
art += '    _ => ("", &[]),\n}\n'
for name, content in [
    ("crates/player-ui/src/builtin_models.in", rust),
    ("docs/MODELS.md", doc),
    ("crates/player-ui/src/gallery_art.in", art),
]:
    path = ROOT / name
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"{name} is stale; run python3 scripts/sync-catalog.py")
    else:
        path.write_text(content)
# The compatibility suites select scenarios, not production UI metadata.
for suite in ("top100", "ign100", "solo"):
    for target in json.loads((ROOT / f"fixtures/compatibility/{suite}-targets.json").read_text()):
        if target.get("sha256"):
            game = by_hash[target["sha256"]]
            for key in ("players", "play_mode"):
                if key in target:
                    assert game.get(key, "") == target[key], (target["title"], key)
print(f"Catalog verified: {len(games)} cartridge identities, {len(models)} models.")
