"""Generate exact-ROM browser metadata from the reviewed compatibility manifest."""

import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
targets = json.loads((root / "fixtures/compatibility/top100-targets.json").read_text())
assert len(targets) == 100 and [t["id"] for t in targets] == list(range(1, 101))
targets += json.loads((root / "fixtures/compatibility/ign100-targets.json").read_text())
games = {
    t["sha256"]: {
        k: t[k]
        for k in ["title", "players", "battery", "region", "play_mode", "peripheral"]
        if k in t
    }
    for t in targets
    if t.get("sha256")
}
(root / "tests/reference-js/game-catalog.mjs").write_text(
    "// Generated by scripts/sync-game-catalog.py. Identity is never inferred from filenames.\nexport const GAMES = "
    + json.dumps(games, indent=2, ensure_ascii=False)
    + ";\n"
)
