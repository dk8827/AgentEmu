#!/usr/bin/env python3
"""Generate cross-language contracts from game packages; --check is a CI drift gate."""

import argparse
import json
import re
import hashlib
import runpy
from pathlib import Path

root = Path(__file__).resolve().parents[1]
a = argparse.ArgumentParser()
a.add_argument("--check", action="store_true")
args = a.parse_args()
tasks = [json.loads(p.read_text()) for p in sorted((root / "integrations").glob("*/task.json"))]
assert tasks and len({t["id"] for t in tasks}) == len(tasks)
assert len({t["observation"] for t in tasks}) == len(tasks)
assert len({t["module"] for t in tasks}) == len(tasks)
for t in tasks:
    assert re.fullmatch("[a-z][a-z0-9_]*", t["module"]) and re.fullmatch(
        "[0-9a-f]{64}", t["rom_sha256"]
    )
    assert len(t["actions"]) == 2
schemas = [
    name
    for t in tasks
    for name in [
        t["observation"],
        t["assistance_observation"],
        *[v["observation"] for v in t.get("policy_variants", [])],
    ]
]
assert len(schemas) == len(set(schemas)), "duplicate observation identifier"
spec = json.loads((root / "integrations/contra-jungle/temporal-observation.json").read_text())
encoder = (root / "crates/game-integrations/src/temporal.rs").read_text().split("#[cfg(test)]")[0]
assert hashlib.sha256(" ".join(encoder.split()).encode()).hexdigest() == spec["encoder_sha256"], (
    "temporal encoder changed: review/version the contract"
)


def q(s):
    return json.dumps(s, ensure_ascii=False)


rust = "// Generated by scripts/sync-integrations.py; edit integrations/*/task.json.\n"
for t in tasks:
    rust += f"pub mod {t['module']} {{\n"
    for key, name in [
        ("architecture", "ARCHITECTURE"),
        ("observation", "SCHEMA"),
        ("rom_sha256", "ROM_SHA256"),
    ]:
        rust += f"    pub const {name}: &str = {q(t[key])};\n"
    rust += "}\n"
rust += "pub const TASKS: &[crate::registry::Definition] = &[\n"
for t in tasks:
    rust += "    crate::registry::Definition {\n"
    rust += f"        policy_observation: crate::{t['module']}::policy_observation,\n"
    for key in [
        "id",
        "architecture",
        "observation",
        "assistance_architecture",
        "assistance_observation",
        "rom_sha256",
        "reset",
        "scope",
    ]:
        rust += f"        {key}: {q(t[key])},\n"
    solo = t.get("solo_reset")
    menu = t.get("solo_menu", [])
    assert bool(solo) == bool(menu)
    assert all(0 < n <= 1200 and len(m) == 2 and 0 <= m[0] <= 255 and m[1] == 0 for n, m in menu)
    rust += f"        solo_reset: {('Some(' + q(solo) + ')') if solo else 'None'},\n"
    rust += (
        "        solo_menu: &[" + ", ".join(f"({n}, [{m[0]}, {m[1]}])" for n, m in menu) + "],\n"
    )
    rust += "        variants: &[\n"
    for v in t.get("policy_variants", []):
        assert v["features"] in ("history", "history-aim") and t["id"] == "contra-jungle"
        assert v["inputs"] == 272 + 24 * (v["features"] == "history-aim") + 12 * v["assistance"]
        rust += (
            "            crate::registry::PolicyVariant { "
            + ", ".join(
                f"{k}: " + (q(v[k]) if isinstance(v[k], str) else str(v[k]).lower())
                for k in ("architecture", "observation", "inputs", "assistance", "features")
            )
            + " },\n"
        )
    rust += "        ],\n"
    rust += f"        actions: [{q(t['actions'][0])}, {q(t['actions'][1])}],\n    }},\n"
rust += "];\n"
py = '"""Generated by scripts/sync-integrations.py. No training dependencies."""\n'
py += (
    "CONTRACTS = "
    + repr({t["id"]: (t["architecture"], t["observation"], t["rom_sha256"]) for t in tasks})
    + "\n"
)
py += (
    "ASSIST_CONTRACTS = "
    + repr(
        {
            t["id"]: (t["assistance_architecture"], t["assistance_observation"], t["rom_sha256"])
            for t in tasks
        }
    )
    + "\n"
)
py += (
    "RESETS = "
    + repr({t["id"]: t["reset"] for t in tasks})
    + '\nROM = CONTRACTS["contra-jungle"][2]\n'
)
py += (
    "POLICY_VARIANTS = "
    + repr(
        {
            v["observation"]: dict(v, task=t["id"], rom_sha256=t["rom_sha256"])
            for t in tasks
            for v in t.get("policy_variants", [])
        }
    )
    + "\n"
)
py += "SOLO_MENUS = " + repr({t["id"]: t["solo_menu"] for t in tasks if "solo_menu" in t}) + "\n"
py += "SOLO_RESETS = " + repr({t["id"]: t["solo_reset"] for t in tasks if "solo_reset" in t}) + "\n"
js = (
    "// Generated by scripts/sync-integrations.py.\nexport const RESETS = "
    + json.dumps({t["id"]: t["reset"] for t in tasks}, indent=2)
    + ";\n"
)
for path, text in [
    ("crates/game-integrations/src/contracts.rs", rust),
    ("training/contra_training/contracts.py", py),
    ("tests/reference-js/task-contracts.mjs", js),
]:
    p = root / path
    if args.check:
        if not p.exists() or p.read_text() != text:
            raise SystemExit(f"{path} is stale; run scripts/sync-integrations.py")
    else:
        p.write_text(text)
# Observation encoding is an equally important cross-language ABI.

runpy.run_path(str(root / "scripts/sync-observations.py"), run_name="__main__")
