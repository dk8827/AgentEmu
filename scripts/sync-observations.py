#!/usr/bin/env python3
"""Validate observation ABIs; generate named Python indices and Rust validation.

Called by sync-integrations.py, including --check in CI. To change a decoder,
review its observation.json names/encodings and deliberately update its digest.
Changing feature meanings/order requires a new schema ID and new model artifacts.
"""

import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
check = argparse.ArgumentParser()
check.add_argument("--check", action="store_true")
args = check.parse_args()
layouts = {}
rust = "// Generated by scripts/sync-observations.py.\n"
rust += "pub const SCHEMAS: &[crate::observations::Schema] = &[\n"
for task_path in sorted((root / "integrations").glob("*/task.json")):
    task = json.loads(task_path.read_text())
    path = task_path.with_name("observation.json")
    spec = json.loads(path.read_text())
    assert spec["schema"] == task["observation"] and spec["width"] == 256
    source = (root / "crates/game-integrations/src" / (task["module"] + ".rs")).read_text()
    source = source[source.index("    pub fn observation(") :]
    source = source[: source.index("\n}\n") + 2]
    digest = hashlib.sha256(" ".join(source.split()).encode()).hexdigest()
    if digest != spec["encoder_sha256"]:
        raise SystemExit(
            f"{path.relative_to(root)}: encoder changed; review the feature ABI and update encoder_sha256 to {digest}"
        )
    fields = {}
    used = set()
    reserved = set(range(256))
    for group in spec["groups"]:
        assert group["stride"] >= len(group["fields"]) and group["repeat"] > 0
        for repeat in range(group["repeat"]):
            prefix = group["name"] + (f"[{repeat}]" if group["repeat"] > 1 else "")
            for offset, field in enumerate(group["fields"]):
                index = group["start"] + repeat * group["stride"] + offset
                name = prefix + "." + field["name"]
                assert 0 <= index < 256 and index not in used and name not in fields, (
                    path,
                    name,
                    index,
                )
                used.add(index)
                if not field["reserved"]:
                    reserved.remove(index)
                    fields[name] = (index, field["encoding"])
    masks = [sum(1 << (i % 64) for i in reserved if i // 64 == block) for block in range(4)]
    layouts[task["id"]] = fields
    rust += (
        "    crate::observations::Schema { id: "
        + json.dumps(spec["schema"])
        + ", reserved: "
        + str(masks)
        + ', json: include_str!("../../../'
        + path.relative_to(root).as_posix()
        + '") },\n'
    )
rust += "];\n"
python = '"""Generated names/indices from integrations/*/observation.json; no ML dependencies."""\n'
python += (
    "LAYOUTS = " + repr(layouts) + "\n\ndef index(game, name):\n    return LAYOUTS[game][name][0]\n"
)
for name, content in [
    ("crates/game-integrations/src/observation_contracts.rs", rust),
    ("training/contra_training/observation_contracts.py", python),
]:
    path = root / name
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"{name} is stale; run scripts/sync-integrations.py")
    else:
        path.write_text(content)
