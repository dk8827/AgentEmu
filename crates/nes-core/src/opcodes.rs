// Official instruction encodings. Unimplemented opcodes fail explicitly.
fn decode(opcode: u8) -> Option<(Op, Mode)> {
    use {Mode::*, Op::*};
    Some(match opcode {
        0x00 => (Brk, Imp),
        0x01 => (Ora, IndX),
        0x05 => (Ora, Zp),
        0x06 => (Asl, Zp),
        0x08 => (Php, Imp),
        0x09 => (Ora, Imm),
        0x0a => (Asl, Acc),
        0x0d => (Ora, Abs),
        0x0e => (Asl, Abs),
        0x10 => (Bpl, Rel),
        0x11 => (Ora, IndY),
        0x15 => (Ora, ZpX),
        0x16 => (Asl, ZpX),
        0x18 => (Clc, Imp),
        0x19 => (Ora, AbsY),
        0x1d => (Ora, AbsX),
        0x1e => (Asl, AbsX),
        0x20 => (Jsr, Abs),
        0x21 => (And, IndX),
        0x24 => (Bit, Zp),
        0x25 => (And, Zp),
        0x26 => (Rol, Zp),
        0x28 => (Plp, Imp),
        0x29 => (And, Imm),
        0x2a => (Rol, Acc),
        0x2c => (Bit, Abs),
        0x2d => (And, Abs),
        0x2e => (Rol, Abs),
        0x30 => (Bmi, Rel),
        0x31 => (And, IndY),
        0x35 => (And, ZpX),
        0x36 => (Rol, ZpX),
        0x38 => (Sec, Imp),
        0x39 => (And, AbsY),
        0x3d => (And, AbsX),
        0x3e => (Rol, AbsX),
        0x40 => (Rti, Imp),
        0x41 => (Eor, IndX),
        0x45 => (Eor, Zp),
        0x46 => (Lsr, Zp),
        0x48 => (Pha, Imp),
        0x49 => (Eor, Imm),
        0x4a => (Lsr, Acc),
        0x4c => (Jmp, Abs),
        0x4d => (Eor, Abs),
        0x4e => (Lsr, Abs),
        0x50 => (Bvc, Rel),
        0x51 => (Eor, IndY),
        0x55 => (Eor, ZpX),
        0x56 => (Lsr, ZpX),
        0x58 => (Cli, Imp),
        0x59 => (Eor, AbsY),
        0x5d => (Eor, AbsX),
        0x5e => (Lsr, AbsX),
        0x60 => (Rts, Imp),
        0x61 => (Adc, IndX),
        0x65 => (Adc, Zp),
        0x66 => (Ror, Zp),
        0x68 => (Pla, Imp),
        0x69 => (Adc, Imm),
        0x6a => (Ror, Acc),
        0x6c => (Jmp, Ind),
        0x6d => (Adc, Abs),
        0x6e => (Ror, Abs),
        0x70 => (Bvs, Rel),
        0x71 => (Adc, IndY),
        0x75 => (Adc, ZpX),
        0x76 => (Ror, ZpX),
        0x78 => (Sei, Imp),
        0x79 => (Adc, AbsY),
        0x7d => (Adc, AbsX),
        0x7e => (Ror, AbsX),
        0x81 => (Sta, IndX),
        0x84 => (Sty, Zp),
        0x85 => (Sta, Zp),
        0x86 => (Stx, Zp),
        0x88 => (Dey, Imp),
        0x8a => (Txa, Imp),
        0x8c => (Sty, Abs),
        0x8d => (Sta, Abs),
        0x8e => (Stx, Abs),
        0x90 => (Bcc, Rel),
        0x91 => (Sta, IndY),
        0x94 => (Sty, ZpX),
        0x95 => (Sta, ZpX),
        0x96 => (Stx, ZpY),
        0x98 => (Tya, Imp),
        0x99 => (Sta, AbsY),
        0x9a => (Txs, Imp),
        0x9d => (Sta, AbsX),
        0xa0 => (Ldy, Imm),
        0xa1 => (Lda, IndX),
        0xa2 => (Ldx, Imm),
        0xa4 => (Ldy, Zp),
        0xa5 => (Lda, Zp),
        0xa6 => (Ldx, Zp),
        0xa8 => (Tay, Imp),
        0xa9 => (Lda, Imm),
        0xaa => (Tax, Imp),
        0xac => (Ldy, Abs),
        0xad => (Lda, Abs),
        0xae => (Ldx, Abs),
        0xb0 => (Bcs, Rel),
        0xb1 => (Lda, IndY),
        0xb4 => (Ldy, ZpX),
        0xb5 => (Lda, ZpX),
        0xb6 => (Ldx, ZpY),
        0xb8 => (Clv, Imp),
        0xb9 => (Lda, AbsY),
        0xba => (Tsx, Imp),
        0xbc => (Ldy, AbsX),
        0xbd => (Lda, AbsX),
        0xbe => (Ldx, AbsY),
        0xc0 => (Cpy, Imm),
        0xc1 => (Cmp, IndX),
        0xc4 => (Cpy, Zp),
        0xc5 => (Cmp, Zp),
        0xc6 => (Dec, Zp),
        0xc8 => (Iny, Imp),
        0xc9 => (Cmp, Imm),
        0xca => (Dex, Imp),
        0xcc => (Cpy, Abs),
        0xcd => (Cmp, Abs),
        0xce => (Dec, Abs),
        0xd0 => (Bne, Rel),
        0xd1 => (Cmp, IndY),
        0xd5 => (Cmp, ZpX),
        0xd6 => (Dec, ZpX),
        0xd8 => (Cld, Imp),
        0xd9 => (Cmp, AbsY),
        0xdd => (Cmp, AbsX),
        0xde => (Dec, AbsX),
        0xe0 => (Cpx, Imm),
        0xe1 => (Sbc, IndX),
        0xe4 => (Cpx, Zp),
        0xe5 => (Sbc, Zp),
        0xe6 => (Inc, Zp),
        0xe8 => (Inx, Imp),
        0xe9 => (Sbc, Imm),
        0xea => (Nop, Imp),
        0xec => (Cpx, Abs),
        0xed => (Sbc, Abs),
        0xee => (Inc, Abs),
        0xf0 => (Beq, Rel),
        0xf1 => (Sbc, IndY),
        0xf5 => (Sbc, ZpX),
        0xf6 => (Inc, ZpX),
        0xf8 => (Sed, Imp),
        0xf9 => (Sbc, AbsY),
        0xfd => (Sbc, AbsX),
        0xfe => (Inc, AbsX),
        _ => return None,
    })
}
